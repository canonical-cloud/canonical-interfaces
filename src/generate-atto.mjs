// Generated AttoLang scalar/collection admission bounds. No JSON codec or transport.
import { snake } from "./generate.mjs";

const kindFor = (schema) => {
  const declared = Array.isArray(schema.type) ? schema.type : [schema.type];
  // JSON Schema type arrays must be unique. In particular, multiple "null"
  // entries cannot silently collapse into a supported constrained type.
  if (new Set(declared).size !== declared.length) return null;
  const types = declared.filter((t) => t !== "null");
  if (types.length !== 1) return null;
  return { integer: "value", string: "length", array: "count" }[types[0]] || null;
};

export function emitAttoBounds(types) {
  const out = [
    "// AUTOGENERATED by src/generate-atto.mjs; do not edit.",
    "// Bounds-only AttoLang projection of canonical-interfaces JSON Schema.",
    "// Callers must validate JSON shapes, required fields, encodings, and enum values separately.",
    "// For string fields, length means Unicode scalar count (not UTF-8 bytes).",
    "",
  ];
  const emitted = new Set();
  for (const type of types) {
    for (const property of type.props) {
      const schema = property.schema;
      if (!schema || typeof schema !== "object" || Array.isArray(schema)) {
        throw new Error("AttoLang invalid property schema: " + type.name + "." + property.name);
      }
      const boundKeywords = [
        "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf",
        "minLength", "maxLength", "minItems", "maxItems",
      ].filter((key) => Object.hasOwn(schema, key));
      if (boundKeywords.length === 0) continue;
      const kind = kindFor(schema);
      if (!kind) {
        throw new Error("AttoLang unsupported constrained type: " + type.name + "." + property.name);
      }
      const lowKey = kind === "value" ? "minimum" : kind === "length" ? "minLength" : "minItems";
      const highKey = kind === "value" ? "maximum" : kind === "length" ? "maxLength" : "maxItems";
      const unsupported = boundKeywords.filter((key) => key !== lowKey && key !== highKey);
      if (unsupported.length) {
        throw new Error("AttoLang unsupported bound keyword for " + type.name + "." + property.name + ": " + unsupported.join(", "));
      }
      const lower = schema[lowKey] === undefined ? (kind === "value" ? null : 0) : schema[lowKey];
      const upper = schema[highKey] === undefined ? null : schema[highKey];
      for (const [label, bound] of [["minimum", lower], ["maximum", upper]]) {
        if (bound !== null && (!Number.isSafeInteger(bound) || (kind !== "value" && bound < 0))) {
          throw new Error("AttoLang " + type.name + "." + property.name + ": " + label + " must be a safe integer, nonnegative for length/count");
        }
      }
      if (lower !== null && upper !== null && lower > upper) {
        throw new Error("AttoLang " + type.name + "." + property.name + ": minimum exceeds maximum");
      }
      const name = "within_" + snake(type.name) + "_" + snake(property.name) + "_" + kind;
      if (!/^within_[a-z0-9_]+$/.test(name) || emitted.has(name)) {
        throw new Error("AttoLang duplicate or invalid export name: " + name);
      }
      emitted.add(name);
      out.push("pub fnc " + name + "(int " + kind + "): bool {");
      if (lower !== null) out.push("  if " + kind + " < " + lower + " then return false; fi");
      if (upper !== null) out.push("  if " + kind + " > " + upper + " then return false; fi");
      out.push("  return true;", "}", "");
    }
  }
  if (emitted.size === 0) throw new Error("AttoLang bound projection must not silently become empty");
  return { "atto/bounds.atto": out.join("\n") };
}
