// Source-only AttoLang contract introspection projection.
// This intentionally does not pretend to validate JSON or implement a transport.
const TYPE_NAME = /^[A-Z][A-Za-z0-9]*$/;
const FIELD_NAME = /^[a-z][A-Za-z0-9_]*$/;
const REF_NAME = /^#\/\$defs\/([A-Z][A-Za-z0-9]*)$/;

function symbol(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

function wireKind(schema) {
  if (!schema || typeof schema !== "object" || Array.isArray(schema)) {
    throw new Error("Atto projection requires a field schema");
  }
  if (schema.$ref !== undefined) {
    if (Object.hasOwn(schema, "type") || Object.hasOwn(schema, "enum")) {
      throw new Error("Atto projection cannot flatten a reference with extra type or enum constraints");
    }
    const match = REF_NAME.exec(schema.$ref);
    if (!match) throw new Error(`Atto projection refuses external reference ${schema.$ref}`);
    return `ref:${match[1]}`;
  }
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  if (types.some((kind) => typeof kind !== "string") ||
      new Set(types).size !== types.length) {
    throw new Error("Atto projection rejects duplicated or invalid union members");
  }
  if (schema.enum !== undefined && (!Array.isArray(schema.enum) || schema.enum.length === 0)) {
    throw new Error("Atto projection requires a nonempty enum array");
  }
  const kinds = types.filter((kind) => kind !== "null" && kind !== undefined);
  if (kinds.length !== 1) throw new Error("Atto projection cannot describe a multi-type union");
  const kind = kinds[0];
  if (!["string", "integer", "number", "boolean", "array", "object"].includes(kind)) {
    throw new Error(`Atto projection cannot describe schema type ${kind}`);
  }
  return `${kind}${types.includes("null") ? ":nullable" : ""}${Array.isArray(schema.enum) ? ":enum" : ""}`;
}

function literal(value) {
  return JSON.stringify(value);
}

export function emitAttoContractIndex(types) {
  if (!Array.isArray(types) || types.length === 0) throw new Error("Atto projection needs schema types");
  const names = new Set();
  const symbols = new Set();
  const ordered = [...types].sort((left, right) => left.name.localeCompare(right.name, "en"));
  const lines = [
    "// AUTOGENERATED by src/generate-output.mjs from schema/index.json.",
    "// Contract introspection only: not a JSON validator, runtime SDK, or compiler conformance claim.",
    "// Do not edit; change schema/ then regenerate.",
    "",
    `pub fnc canonical_interface_type_count(): int { return ${ordered.length}; }`,
    "",
  ];

  for (const type of ordered) {
    if (!TYPE_NAME.test(type.name) || names.has(type.name)) {
      throw new Error(`invalid or duplicated Atto type: ${type.name}`);
    }
    names.add(type.name);
    const id = symbol(type.name);
    if (symbols.has(id)) throw new Error(`Atto symbol collision: ${id}`);
    symbols.add(id);
    if (!Array.isArray(type.props)) throw new Error(`Atto type ${type.name} lacks props`);
    lines.push(`pub fnc canonical_${id}_type_name(): string { return ${literal(type.name)}; }`);
    lines.push(`pub fnc canonical_${id}_field_count(): int { return ${type.props.length}; }`);
    const fields = new Set();
    for (const [index, field] of type.props.entries()) {
      if (!FIELD_NAME.test(field.name) || fields.has(field.name)) {
        throw new Error(`invalid or duplicated Atto field: ${type.name}.${field.name}`);
      }
      fields.add(field.name);
      const prefix = `canonical_${id}_field_${index}`;
      lines.push(`pub fnc ${prefix}_name(): string { return ${literal(field.name)}; }`);
      lines.push(`pub fnc ${prefix}_wire_kind(): string { return ${literal(wireKind(field.schema))}; }`);
      lines.push(`pub fnc ${prefix}_required(): bool { return ${field.required === true}; }`);
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}
